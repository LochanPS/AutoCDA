/**
 * One-time setup: generate the Pro signing keypair.
 *
 *   node scripts/gen-pro-keypair.mjs
 *
 * Writes:
 *   .secrets/pro-private.jwk   PRIVATE key — mints Pro keys. KEEP SECRET, never commit.
 *   src/pro/proPublicKey.js    PUBLIC key — verifies keys in the app. Safe to commit & ship.
 *
 * After running: commit src/pro/proPublicKey.js, redeploy, then mint keys with
 * scripts/mint-pro-key.mjs. Re-running REPLACES the keypair and invalidates every
 * key minted with the old one, so only run it again if you mean to rotate.
 */
import { webcrypto as crypto } from "node:crypto";
import { writeFile, mkdir, access } from "node:fs/promises";

const PRIV = ".secrets/pro-private.jwk";
try {
  await access(PRIV);
  console.error(`Refusing to overwrite existing ${PRIV}. Delete it first to rotate the keypair.`);
  process.exit(1);
} catch { /* not present — good */ }

const kp = await crypto.subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, ["sign", "verify"]);
const priv = await crypto.subtle.exportKey("jwk", kp.privateKey);
const pub = await crypto.subtle.exportKey("jwk", kp.publicKey);

await mkdir(".secrets", { recursive: true });
await writeFile(PRIV, JSON.stringify(priv, null, 2) + "\n");
await writeFile(
  "src/pro/proPublicKey.js",
  "// Pro signing PUBLIC key — safe to commit and ship (verifies keys, cannot mint them).\n" +
  "// AUTO-GENERATED by scripts/gen-pro-keypair.mjs. To rotate: delete .secrets/pro-private.jwk and re-run.\n" +
  `export const PRO_PUBLIC_JWK = ${JSON.stringify(pub)};\n`
);

console.log("✓ Wrote .secrets/pro-private.jwk  (SECRET — keep it safe, it is gitignored)");
console.log("✓ Wrote src/pro/proPublicKey.js   (commit this, then redeploy)");
console.log("\nNext: mint a key →  node scripts/mint-pro-key.mjs you@example.com");
